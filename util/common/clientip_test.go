package common

import "testing"

// 回归护栏:登录爆破节流以 ClientIP 为 key,伪造 X-Forwarded-For 曾能让节流完全失效。
func TestClientIP(t *testing.T) {
	cases := []struct {
		name       string
		remoteAddr string
		xff        string
		want       string
	}{
		// 公网直连:XFF 一律不可信,必须落到真实对端
		{"公网直连伪造 XFF", "203.0.113.9:51234", "1.2.3.4", "203.0.113.9"},
		{"公网直连伪造 XFF 链", "203.0.113.9:51234", "1.2.3.4, 5.6.7.8", "203.0.113.9"},
		{"公网直连无 XFF", "203.0.113.9:51234", "", "203.0.113.9"},

		// 本机/内网反代:XFF 可信,取最左原始客户端
		{"本机 nginx 反代", "127.0.0.1:40000", "198.51.100.7", "198.51.100.7"},
		{"内网反代", "10.0.0.5:40000", "198.51.100.7, 10.0.0.5", "198.51.100.7"},
		{"内网反代带空格", "192.168.1.2:40000", "  198.51.100.7 , 192.168.1.2", "198.51.100.7"},
		{"IPv6 回环反代", "[::1]:40000", "198.51.100.7", "198.51.100.7"},

		// 可信反代但 XFF 是垃圾值 → 退回直连对端,不让脏数据进节流表
		{"可信反代 XFF 非法", "127.0.0.1:40000", "not-an-ip", "127.0.0.1"},
		{"可信反代 XFF 空段", "127.0.0.1:40000", " , 1.2.3.4", "127.0.0.1"},

		// 边界
		{"无端口的 RemoteAddr", "203.0.113.9", "1.2.3.4", "203.0.113.9"},
		{"空 RemoteAddr", "", "1.2.3.4", ""},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := ClientIP(c.remoteAddr, c.xff); got != c.want {
				t.Fatalf("ClientIP(%q, %q) = %q, want %q", c.remoteAddr, c.xff, got, c.want)
			}
		})
	}
}
